-- Admin membership reporting foundation.
--
-- This migration deliberately does not create new membership, attendance,
-- household, session or journal systems. It adds the minimum immutable metadata
-- required to report those existing systems accurately over time:
--   * membership status transitions (profiles remains the current-state mirror)
--   * journal field empty/non-empty transitions (never journal content)
--   * database-driven programme locations
--   * subscription MRR snapshots captured from future Stripe webhook events
--
-- Historical warning: the baseline rows written below describe state at the
-- moment this migration runs. They are not backdated and must not be presented
-- as reconstructed history.

-- ---------------------------------------------------------------------------
-- 1. Dynamic programme locations and future facilitator attribution
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.programme_locations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  timezone text NOT NULL DEFAULT 'Pacific/Auckland',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.programme_locations ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.programme_locations TO authenticated;
GRANT ALL ON public.programme_locations TO service_role;

DROP POLICY IF EXISTS "programme_locations_authenticated_read" ON public.programme_locations;
CREATE POLICY "programme_locations_authenticated_read" ON public.programme_locations
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "programme_locations_admin_manage" ON public.programme_locations;
CREATE POLICY "programme_locations_admin_manage" ON public.programme_locations
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'::app_role))
  WITH CHECK (public.has_role(auth.uid(), 'admin'::app_role));

INSERT INTO public.programme_locations (code, name)
VALUES ('taupo', 'Taupō')
ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name;

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS home_location_id uuid
    REFERENCES public.programme_locations(id) ON DELETE SET NULL;

ALTER TABLE public.scheduled_sessions
  ADD COLUMN IF NOT EXISTS location_id uuid
    REFERENCES public.programme_locations(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS facilitator_profile_id uuid
    REFERENCES public.profiles(id) ON DELETE SET NULL;

ALTER TABLE public.scheduled_sessions
  DROP CONSTRAINT IF EXISTS scheduled_sessions_session_date_track_key;

CREATE UNIQUE INDEX IF NOT EXISTS scheduled_sessions_date_track_location_key
  ON public.scheduled_sessions (session_date, track, location_id) NULLS NOT DISTINCT;

-- Mindcast currently operates in Taupō. The value is a seeded database row,
-- not a UI constant; future locations automatically flow into report filters.
UPDATE public.profiles
SET home_location_id = (SELECT id FROM public.programme_locations WHERE code = 'taupo')
WHERE home_location_id IS NULL;

UPDATE public.scheduled_sessions
SET location_id = (SELECT id FROM public.programme_locations WHERE code = 'taupo')
WHERE location_id IS NULL;

CREATE OR REPLACE FUNCTION public.assign_default_programme_location()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.location_id IS NULL THEN
    SELECT id INTO NEW.location_id
    FROM public.programme_locations
    WHERE is_active
    ORDER BY CASE WHEN code = 'taupo' THEN 0 ELSE 1 END, created_at
    LIMIT 1;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS assign_default_programme_location ON public.scheduled_sessions;
CREATE TRIGGER assign_default_programme_location
  BEFORE INSERT OR UPDATE ON public.scheduled_sessions
  FOR EACH ROW EXECUTE FUNCTION public.assign_default_programme_location();

CREATE INDEX IF NOT EXISTS profiles_home_location_idx
  ON public.profiles (home_location_id);
CREATE INDEX IF NOT EXISTS scheduled_sessions_reporting_idx
  ON public.scheduled_sessions (session_date, track, location_id, status);
