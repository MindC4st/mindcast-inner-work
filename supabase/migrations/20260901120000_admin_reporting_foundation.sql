CREATE OR REPLACE FUNCTION public.admin_reporting_metric_definitions()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin'::app_role) THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  RETURN jsonb_build_object(
    'active_member', 'A profile whose effective membership status is active or trialing. This matches the paid-content access gate; past_due is reported separately.',
    'paying_member', 'A profile or household covered by a Stripe subscription whose current status is active. Trialing is not counted as paying.',
    'eligible_session', 'A non-cancelled scheduled session on or after reporting capture, in the member''s track and location, occurring while their membership status interval is active or trialing.',
    'attended', 'At least one valid check_ins record for the profile and scheduled session. Duplicate check-ins count once.',
    'missed', 'An eligible session with no valid check-in. A person is never missed before membership starts, after it ends, at another track/location, or for a cancelled session.',
    'attendance_rate', 'Distinct eligible sessions attended divided by eligible sessions available.',
    'return_after_miss', 'Missed eligible-session outcomes whose next eligible session was attended, divided by misses with a subsequent eligible session.',
    'journal_entry', 'A persisted Adult-track journal field changing from empty to a meaningful non-empty response. No response content is copied into reporting.',
    'journal_completion', 'Currently completed available Adult journal fields divided by fields available for that member/week. Teen and Child are paper-only and display N/A.',
    'retention', 'Members with a non-baseline active start who are still active at the stated duration, divided only by starts old enough to reach that duration.',
    'churn', 'Members transitioning from active/trialing to a terminal lapsed/none state during a period divided by active/trialing members at the beginning. Paused and past_due remain visible but are not cancellation churn.',
    'historical_coverage', 'Status and journal transition history is reliable from reporting_history_started_at. Migration baselines are current-state facts, not backdated history.'
  );
END;
$$;

REVOKE ALL ON FUNCTION public.admin_reporting_metric_definitions() FROM PUBLIC, anon;
