)
RETURNS public.investor_reports
LANGUAGE plpgsql VOLATILE SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_report public.investor_reports;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin'::app_role) THEN
    RAISE EXCEPTION 'not authorized';
  END IF;
  IF p_metrics_snapshot IS NULL OR p_metrics_snapshot = '{}'::jsonb
     OR NULLIF(btrim(p_generated_html), '') IS NULL
     OR NULLIF(btrim(p_generated_text), '') IS NULL THEN
    RAISE EXCEPTION 'A metric snapshot and final HTML/text are required.';
  END IF;

  UPDATE public.investor_reports
  SET status = 'sent', metrics_snapshot = p_metrics_snapshot,
      generated_html = p_generated_html, generated_text = p_generated_text,
      sent_at = now(), sent_by = auth.uid(), updated_by = auth.uid(),
      metrics_refreshed_at = COALESCE(metrics_refreshed_at, now())
  WHERE id = p_report_id AND status IN ('draft', 'ready')
  RETURNING * INTO v_report;

  IF v_report.id IS NULL THEN
    RAISE EXCEPTION 'Report was not found or is already immutable.';
  END IF;

  INSERT INTO public.investor_report_audit (report_id, event, actor_id, detail)
  VALUES (v_report.id, 'sent', auth.uid(), jsonb_build_object(
    'subject', v_report.subject,
    'metric_definition_version', v_report.metric_definition_version
  ));
  RETURN v_report;
END;
$$;

