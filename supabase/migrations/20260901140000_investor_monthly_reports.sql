CREATE OR REPLACE FUNCTION public.admin_investor_billing_snapshot(
  p_as_of timestamptz,
  p_period_start timestamptz DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_capture_at timestamptz;
  v_result jsonb;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin'::app_role) THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT value::timestamptz INTO v_capture_at
  FROM public.app_settings
  WHERE key = 'investor_billing_history_started_at';

  IF v_capture_at IS NULL OR p_as_of < v_capture_at THEN
    RETURN jsonb_build_object(
      'available', false,
      'capture_started_at', v_capture_at,
      'reason', 'Billing history was not captured at this reporting cutoff.'
    );
  END IF;

  WITH latest AS (
    SELECT DISTINCT ON (subscription_id)
      subscription_id, profile_id, household_id, status, mrr_cents, currency
    FROM public.subscription_reporting_events
    WHERE effective_at <= p_as_of
    ORDER BY subscription_id, effective_at DESC, id DESC
  ),
  active_subscriptions AS (
    SELECT * FROM latest WHERE status = 'active'
  ),
  active_members AS (
    SELECT DISTINCT d.profile_id
    FROM public.reporting_member_dimension d
    JOIN public.reporting_membership_intervals mi
      ON mi.profile_id = d.profile_id
     AND mi.status IN ('active','trialing')
     AND mi.starts_at <= p_as_of
     AND (mi.ends_at IS NULL OR mi.ends_at > p_as_of)
    JOIN active_subscriptions s
      ON s.profile_id = d.profile_id
      OR (s.household_id IS NOT NULL AND s.household_id = d.household_id)
  ),
  transitions AS (
    SELECT e.*,
      lag(status) OVER (
        PARTITION BY subscription_id ORDER BY effective_at, id
      ) AS previous_status
    FROM public.subscription_reporting_events e
  ),
  resolved_trials AS (
    SELECT * FROM transitions
    WHERE p_period_start IS NOT NULL
      AND effective_at >= p_period_start
      AND effective_at <= p_as_of
      AND previous_status = 'trialing'
      AND status <> 'trialing'
  )
  SELECT jsonb_build_object(
    'available', true,
    'capture_started_at', v_capture_at,
    'as_of', p_as_of,
    'active_subscriptions', (SELECT count(*) FROM active_subscriptions),
    'active_paying_members', (SELECT count(*) FROM active_members),
    'mrr_cents', (
      SELECT CASE
        WHEN count(*) = 0 THEN 0
        WHEN count(mrr_cents) <> count(*) OR count(DISTINCT currency) <> 1 THEN NULL
        ELSE sum(mrr_cents)
      END
      FROM active_subscriptions
    ),
    'currency', (SELECT min(currency) FROM active_subscriptions),
    'trial_to_paid_numerator', (
      SELECT count(*) FROM resolved_trials WHERE status = 'active'
    ),
    'trial_to_paid_denominator', (SELECT count(*) FROM resolved_trials),
    'trial_to_paid_percent', (
      SELECT CASE WHEN count(*) = 0 THEN NULL
        ELSE round(count(*) FILTER (WHERE status = 'active')::numeric / count(*)::numeric * 100, 1)
      END FROM resolved_trials
    )
  ) INTO v_result;

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_investor_billing_snapshot(timestamptz,timestamptz) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_investor_billing_snapshot(timestamptz,timestamptz) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_investor_report_metrics(p_report_month date)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_month date := date_trunc('month', p_report_month)::date;
  v_current_month date := date_trunc('month', now() AT TIME ZONE 'Pacific/Auckland')::date;
  v_month_end date;
  v_previous_month date;
  v_previous_end date;
  v_trend_start date;
  v_cutoff timestamptz;
  v_previous_cutoff timestamptz;
  v_selected jsonb;
  v_previous jsonb;
  v_trend jsonb;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin'::app_role) THEN
    RAISE EXCEPTION 'not authorized';
  END IF;
  IF p_report_month IS NULL THEN
    RAISE EXCEPTION 'report month is required';
  END IF;
  IF v_month > v_current_month THEN
    RAISE EXCEPTION 'Future investor report months are not enabled.';
  END IF;

  v_month_end := CASE WHEN v_month = v_current_month
    THEN (now() AT TIME ZONE 'Pacific/Auckland')::date
    ELSE (v_month + interval '1 month - 1 day')::date END;
  v_previous_month := (v_month - interval '1 month')::date;
  v_previous_end := (v_month - interval '1 day')::date;
  v_trend_start := (v_month - interval '5 months')::date;

  -- Noon is used by the shared attendance layer for date-only programme
  -- sessions; end-of-day here is the month-end subscription snapshot.
  v_cutoff := CASE WHEN v_month = v_current_month THEN now()
    ELSE ((v_month + interval '1 month')::timestamp AT TIME ZONE 'Pacific/Auckland') - interval '1 microsecond' END;
  v_previous_cutoff := (v_month::timestamp AT TIME ZONE 'Pacific/Auckland') - interval '1 microsecond';

  v_selected := public.admin_reporting_dashboard(v_month, v_month_end, NULL, NULL, NULL, NULL);
  v_previous := public.admin_reporting_dashboard(v_previous_month, v_previous_end, NULL, NULL, NULL, NULL);
  v_trend := public.admin_reporting_dashboard(v_trend_start, v_month_end, NULL, NULL, NULL, NULL);

  -- The shared dashboard also contains Admin-only member drill-down rows.
  -- They are deliberately removed here: the investor builder needs aggregates
  -- only and must never receive member names or per-member histories.
  v_selected := v_selected - ARRAY['member_metrics', 'at_risk'];
  v_previous := v_previous - ARRAY['member_metrics', 'at_risk'];
  v_trend := v_trend - ARRAY['member_metrics', 'at_risk'];

  RETURN jsonb_build_object(
    'report_month', to_char(v_month, 'YYYY-MM'),
    'period_start', v_month,
    'period_end', v_month_end,
    'timezone', 'Pacific/Auckland',
    'is_incomplete_month', v_month = v_current_month,
    'metric_definition_version', 'admin-reporting-v1',
    'selected', v_selected,
    'previous', v_previous,
    'trend', v_trend,
    'billing', public.admin_investor_billing_snapshot(
      v_cutoff, v_month::timestamp AT TIME ZONE 'Pacific/Auckland'
    ),
    'previous_billing', public.admin_investor_billing_snapshot(
      v_previous_cutoff, v_previous_month::timestamp AT TIME ZONE 'Pacific/Auckland'
    ),
    'billing_trend', (
      SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'month', to_char(month_start, 'YYYY-MM'),
        'snapshot', public.admin_investor_billing_snapshot(
          CASE WHEN month_start::date = v_current_month THEN now()
            ELSE ((month_start::date + interval '1 month')::timestamp AT TIME ZONE 'Pacific/Auckland') - interval '1 microsecond' END,
          month_start::date::timestamp AT TIME ZONE 'Pacific/Auckland'
        )
      ) ORDER BY month_start), '[]'::jsonb)
      FROM generate_series(v_trend_start, v_month, interval '1 month') AS months(month_start)
    ),
    'operations', jsonb_build_object(
      'active_locations', (
        SELECT count(DISTINCT location_id)
        FROM public.scheduled_sessions
        WHERE status <> 'cancelled'
          AND session_date BETWEEN v_month AND v_month_end
          AND location_id IS NOT NULL
      )
    ),
    'membership_snapshot', jsonb_build_object(
      'active_households', (
        SELECT count(DISTINCT d.household_id)
        FROM public.reporting_member_dimension d
        JOIN public.reporting_membership_intervals mi ON mi.profile_id = d.profile_id
        WHERE d.household_id IS NOT NULL
          AND mi.status IN ('active','trialing')
          AND mi.starts_at <= v_cutoff
          AND (mi.ends_at IS NULL OR mi.ends_at > v_cutoff)
      )
    ),
    'previous_membership_snapshot', jsonb_build_object(
      'active_households', (
        SELECT count(DISTINCT d.household_id)
        FROM public.reporting_member_dimension d
        JOIN public.reporting_membership_intervals mi ON mi.profile_id = d.profile_id
        WHERE d.household_id IS NOT NULL
          AND mi.status IN ('active','trialing')
          AND mi.starts_at <= v_previous_cutoff
          AND (mi.ends_at IS NULL OR mi.ends_at > v_previous_cutoff)
      )
    ),
    'previous_operations', jsonb_build_object(
      'active_locations', (
        SELECT count(DISTINCT location_id)
        FROM public.scheduled_sessions
        WHERE status <> 'cancelled'
          AND session_date BETWEEN v_previous_month AND v_previous_end
          AND location_id IS NOT NULL
      )
    ),
    'availability', jsonb_build_object(
      'referral', jsonb_build_object(
        'available', false,
        'reason', 'No reliable member-referral attribution field exists yet.'
      ),
      'cac', jsonb_build_object(
        'available', false,
        'reason', 'Acquisition spend and channel attribution are not yet captured together.'
      ),
      'contribution_margin', jsonb_build_object(
        'available', false,
        'reason', 'Direct location delivery costs are not yet captured.'
      ),
      'facilitator_mix', jsonb_build_object(
        'available', false,
        'reason', 'Sessions have facilitator attribution, but no canonical founder/non-founder flag exists.'
      )
    )
  );
END;
$$;

