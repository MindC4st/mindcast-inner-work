-- MINDCAST monthly investor updates.
--
-- The report builder consumes the same admin_reporting_dashboard RPC used by
-- Admin Insights. Narrative copy and metric selections stay editable while a
-- report is Draft/Ready; Sent rows retain the exact HTML, text and metric JSON
-- delivered to investors. No member-level or journal-content data is stored.

-- ---------------------------------------------------------------------------
-- 1. Future-safe billing history (current subscriptions is only a mirror)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.subscription_reporting_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id uuid NOT NULL REFERENCES public.subscriptions(id) ON DELETE CASCADE,
  profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  household_id uuid REFERENCES public.households(id) ON DELETE SET NULL,
  status text NOT NULL,
  mrr_cents integer,
  currency text,
  effective_at timestamptz NOT NULL DEFAULT now(),
  is_baseline boolean NOT NULL DEFAULT false,
  source text NOT NULL DEFAULT 'subscription_update',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.subscription_reporting_events ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS subscription_reporting_events_subscription_time_idx
  ON public.subscription_reporting_events (subscription_id, effective_at, id);
CREATE INDEX IF NOT EXISTS subscription_reporting_events_status_time_idx
  ON public.subscription_reporting_events (status, effective_at);

CREATE OR REPLACE FUNCTION public.capture_subscription_reporting_event()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT'
     OR NEW.status IS DISTINCT FROM OLD.status
     OR NEW.mrr_cents IS DISTINCT FROM OLD.mrr_cents
     OR NEW.currency IS DISTINCT FROM OLD.currency
     OR NEW.profile_id IS DISTINCT FROM OLD.profile_id
     OR NEW.household_id IS DISTINCT FROM OLD.household_id THEN
    INSERT INTO public.subscription_reporting_events (
      subscription_id, profile_id, household_id, status, mrr_cents, currency,
      effective_at, is_baseline, source
    ) VALUES (
      NEW.id, NEW.profile_id, NEW.household_id, NEW.status, NEW.mrr_cents,
      NEW.currency, now(), false,
      CASE WHEN current_setting('request.jwt.claim.role', true) = 'service_role'
        THEN 'stripe_webhook' ELSE 'subscription_update' END
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS capture_subscription_reporting_event ON public.subscriptions;
CREATE TRIGGER capture_subscription_reporting_event
  AFTER INSERT OR UPDATE OF status, mrr_cents, currency, profile_id, household_id
  ON public.subscriptions
  FOR EACH ROW EXECUTE FUNCTION public.capture_subscription_reporting_event();

-- This is an honest current-state baseline, not reconstructed history.
INSERT INTO public.subscription_reporting_events (
  subscription_id, profile_id, household_id, status, mrr_cents, currency,
  effective_at, is_baseline, source
)
SELECT s.id, s.profile_id, s.household_id, s.status, s.mrr_cents, s.currency,
       now(), true, 'investor_reporting_baseline'
FROM public.subscriptions s
WHERE NOT EXISTS (
  SELECT 1 FROM public.subscription_reporting_events e
  WHERE e.subscription_id = s.id
);

INSERT INTO public.app_settings (key, value)
VALUES ('investor_billing_history_started_at', now()::text)
ON CONFLICT (key) DO NOTHING;

CREATE OR REPLACE VIEW public.reporting_subscription_intervals AS
SELECT
  e.subscription_id,
  e.profile_id,
  e.household_id,
  e.status,
  e.mrr_cents,
  e.currency,
  e.effective_at AS starts_at,
  lead(e.effective_at) OVER (
    PARTITION BY e.subscription_id ORDER BY e.effective_at, e.id
  ) AS ends_at,
  e.is_baseline,
  e.source
FROM public.subscription_reporting_events e;

REVOKE ALL ON public.reporting_subscription_intervals FROM PUBLIC, anon, authenticated;

