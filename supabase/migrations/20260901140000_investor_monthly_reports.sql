CREATE OR REPLACE FUNCTION public.admin_create_investor_report_revision(p_report_id uuid)
RETURNS public.investor_reports
LANGUAGE plpgsql VOLATILE SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_source public.investor_reports;
  v_report public.investor_reports;
  v_version integer;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin'::app_role) THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT * INTO v_source FROM public.investor_reports WHERE id = p_report_id;
  IF v_source.id IS NULL OR v_source.status NOT IN ('sent','archived') THEN
    RAISE EXCEPTION 'Only a Sent or Archived report can be revised.';
  END IF;
  SELECT COALESCE(max(version), 0) + 1 INTO v_version
  FROM public.investor_reports WHERE report_month = v_source.report_month;

  INSERT INTO public.investor_reports (
    report_month, version, revision_of, status, subject, preheader, headline,
    good, bad, ugly, learned_headline, learned_body, customer_quote,
    customer_quote_attribution, behaviour_change_numerator,
    behaviour_change_denominator, behaviour_change_period,
    behaviour_change_notes, family_signal_label, family_signal_numerator,
    family_signal_denominator, family_signal_notes, one_ask,
    selected_metric_ids, metrics_snapshot, metric_definition_version,
    metrics_refreshed_at, created_by, updated_by
  ) VALUES (
    v_source.report_month, v_version, v_source.id, 'draft', v_source.subject,
    v_source.preheader, v_source.headline, v_source.good, v_source.bad,
    v_source.ugly, v_source.learned_headline, v_source.learned_body,
    v_source.customer_quote, v_source.customer_quote_attribution,
    v_source.behaviour_change_numerator, v_source.behaviour_change_denominator,
    v_source.behaviour_change_period, v_source.behaviour_change_notes,
    v_source.family_signal_label, v_source.family_signal_numerator,
    v_source.family_signal_denominator, v_source.family_signal_notes,
    v_source.one_ask, v_source.selected_metric_ids, v_source.metrics_snapshot,
    v_source.metric_definition_version, v_source.metrics_refreshed_at,
    auth.uid(), auth.uid()
  ) RETURNING * INTO v_report;

  INSERT INTO public.investor_report_priorities
    (report_id, position, objective, target, status, outcome)
  SELECT v_report.id, position, objective, target, status, outcome
  FROM public.investor_report_priorities WHERE report_id = v_source.id;

  INSERT INTO public.investor_report_audit (report_id, event, actor_id, detail)
  VALUES (v_report.id, 'revision_created', auth.uid(),
          jsonb_build_object('revision_of', v_source.id, 'version', v_version));
  RETURN v_report;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_create_investor_report_revision(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_create_investor_report_revision(uuid) TO authenticated;
