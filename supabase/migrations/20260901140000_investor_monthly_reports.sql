CREATE OR REPLACE FUNCTION public.protect_sent_investor_report()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'DELETE' AND OLD.status IN ('sent', 'archived') THEN
    RAISE EXCEPTION 'Sent investor reports are immutable; create a revision instead.';
  END IF;

  IF TG_OP = 'UPDATE' AND OLD.status IN ('sent', 'archived') THEN
    IF NOT (
      OLD.status = 'sent'
      AND NEW.status = 'archived'
      AND (to_jsonb(NEW) - ARRAY['status','updated_at','updated_by'])
          = (to_jsonb(OLD) - ARRAY['status','updated_at','updated_by'])
    ) THEN
      RAISE EXCEPTION 'Sent investor reports are immutable; create a revision instead.';
    END IF;
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS protect_sent_investor_report ON public.investor_reports;
CREATE TRIGGER protect_sent_investor_report
  BEFORE UPDATE OR DELETE ON public.investor_reports
  FOR EACH ROW EXECUTE FUNCTION public.protect_sent_investor_report();

CREATE OR REPLACE FUNCTION public.protect_sent_investor_priority()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_report_id uuid;
  v_status text;
BEGIN
  v_report_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.report_id ELSE NEW.report_id END;
  SELECT status INTO v_status FROM public.investor_reports WHERE id = v_report_id;
  IF v_status IN ('sent', 'archived') THEN
    RAISE EXCEPTION 'Priorities on Sent investor reports are immutable; create a revision instead.';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

