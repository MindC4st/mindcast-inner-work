const esc = (s) => (s || '').replace(/\s+\n/g, '\n').trim();
function q(tag, value) {
  const v = esc(value);
  if (v.includes('$' + tag + '$')) throw new Error('tag collision: ' + tag);
  return `$${tag}$${v}$${tag}$`;
}
function splitBook(book) {
  const m = (book || '').match(/^(.+?)\s+—\s+(.*)$/);
  if (!m) return { title: book || '', author: '', extra: '' };
  const title = m[1].trim();
  let rest = m[2].trim();
  const am = rest.match(/^([A-Z][\w'.-]+(?:\s+[A-Z][\w'.-]+){0,4})(?:\s*\(([^)]*)\))?\s*(?:\s+or\s+(.*))?$/);
  if (am) return { title, author: am[1] + (am[2] ? ` (${am[2]})` : ''), extra: am[3] || '' };
  return { title, author: '', extra: rest };
}

